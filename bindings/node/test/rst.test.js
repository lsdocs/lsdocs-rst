'use strict'

// Parsing, the tree, settings, writers, and extensions written in JS.

const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

const rst = require('..')
const { DirectiveError, Parser } = rst

const DOC = 'Title\n=====\n\nHello, *world*.\n'

test('parse and read the tree', () => {
  const doc = rst.parse(DOC, { transforms: true })
  assert.equal(doc.kind, 'document')
  assert.equal(doc.attributes?.title, 'Title')
  const [emphasis] = rst.findAll(doc, 'emphasis')
  assert.equal(rst.astext(emphasis), 'world')
  assert.deepEqual(emphasis.span, { start: 20, end: 27 })
  assert.deepEqual(
    [...rst.traverse(doc)].map((e) => e.kind),
    ['document', 'title', 'paragraph', 'emphasis'],
  )
  assert.ok(rst.pformat(doc).startsWith('<document ids="title" names="title" title="Title">\n'))
})

test('trees are plain JSON', () => {
  const doc = rst.parse(DOC, { transforms: true })
  assert.deepEqual(JSON.parse(JSON.stringify(doc)), doc)
  assert.deepEqual(doc.children?.[1], {
    kind: 'paragraph',
    children: [
      { text: 'Hello, ', span: { start: 13, end: 20 } },
      {
        kind: 'emphasis',
        children: [{ text: 'world', span: { start: 20, end: 27 } }],
        span: { start: 20, end: 27 },
      },
      { text: '.', span: { start: 27, end: 28 } },
    ],
    span: { start: 13, end: 28 },
  })
})

test('built trees print', () => {
  const tree = { kind: 'document', children: [{ kind: 'paragraph', attributes: { classes: ['x'] }, children: [{ text: 'hi' }] }] }
  assert.equal(rst.pformat(tree), '<document>\n    <paragraph classes="x">\n        hi\n')
  assert.equal(
    rst.toXml(tree, { xmlDeclaration: false, doctypeDeclaration: false }),
    '<!-- Generated by lsdocs-rst -->\n<document><paragraph classes="x">hi</paragraph></document>',
  )
})

test('settings', () => {
  const doc = rst.parse('See PEP 8.\n', { settings: { pep_references: true } })
  const [reference] = rst.findAll(doc, 'reference')
  assert.equal(reference.attributes?.refuri, 'https://peps.python.org/pep-0008')
  assert.equal(new Parser({ settings: { tab_width: 4 } }).settings.tab_width, 4)
  assert.equal(rst.defaultSettings().auto_id_prefix, '%')
  assert.throws(() => rst.parse('x\n', { settings: /** @type {any} */ ({ tabwidth: 4 }) }), /tabwidth/)
  assert.throws(() => new Parser(/** @type {any} */ ({ tabWidth: 4 })), /unknown parser option "tabWidth"/)
})

test('messages outside the tree', () => {
  const { document, messages } = rst.parseWithMessages('See missing_.\n', { transforms: true })
  const [problematic] = rst.findAll(document, 'problematic')
  assert.equal(messages.length, 1)
  const ids = /** @type {string[]} */ (messages[0].attributes?.ids)
  assert.ok(ids.includes(/** @type {string} */ (problematic.attributes?.refid)))
  assert.equal(rst.astext(messages[0]), 'Unknown target name: "missing".')
})

test('makeId', () => {
  assert.equal(rst.makeId('Hello, World!'), 'hello-world')
})

/** @type {import('..').Directive} */
const shout = {
  requiredArguments: 1,
  finalArgumentWhitespace: true,
  optionSpec: { class: 'class_option', level: ['low', 'high'], loud: 'flag' },
  run(ctx) {
    const [nodes, messages] = ctx.parseInline(ctx.arguments[0].toUpperCase())
    /** @type {import('..').Element} */
    const paragraph = { kind: 'paragraph', attributes: { classes: ctx.options.class ?? [] }, children: nodes }
    if ('loud' in ctx.options) paragraph.attributes = { ...paragraph.attributes, loud: ctx.options.level ?? 'low' }
    return [paragraph, ...messages]
  },
}

/** @type {import('..').Directive} */
const box = {
  hasContent: true,
  run(ctx) {
    if (ctx.content.length === 0) throw new DirectiveError(`The "${ctx.name}" directive is empty.`, rst.WARNING)
    return [ctx.parseContent({ kind: 'container', attributes: { classes: ['box'] } })]
  },
}

test('a directive with options', () => {
  const parser = new Parser({ directives: { shout } })
  const doc = parser.parse('.. shout:: hello *world*\n   :class: Big One\n   :loud:\n   :level: HIGH\n')
  assert.equal(
    rst.pformat(doc),
    '<document>\n' +
      '    <paragraph classes="big one" loud="high">\n' +
      '        HELLO \n' +
      '        <emphasis>\n' +
      '            WORLD\n',
  )
  const [message] = rst.findAll(parser.parse('.. shout:: x\n   :level: medium\n'), 'system_message')
  assert.equal(message.attributes?.type, 'ERROR')
  assert.ok(rst.astext(message).includes('invalid option value: (option: "level"; value: \'medium\')'))
})

test('nested JS directives', () => {
  const parser = new Parser({ directives: { box, shout } })
  const doc = parser.parse('.. box::\n\n   .. box::\n\n      .. shout:: deep\n\n   Para.\n')
  assert.deepEqual(
    [...rst.traverse(doc)].map((e) => e.kind),
    ['document', 'container', 'container', 'paragraph', 'paragraph'],
  )
  assert.equal(rst.astext(doc), 'DEEPPara.')
})

test('DirectiveError is a message', () => {
  const doc = new Parser({ directives: { box } }).parse('.. box::\n')
  const [message] = rst.findAll(doc, 'system_message')
  assert.equal(message.attributes?.type, 'WARNING')
  assert.ok(rst.astext(message).startsWith('The "box" directive is empty.'))
})

test('other exceptions are thrown by parse', () => {
  const broken = { run() { throw new RangeError('oops') } }
  assert.throws(() => new Parser({ directives: { broken } }).parse('.. broken::\n'), RangeError)
})

test('a context dies with its directive', () => {
  /** @type {import('..').DirectiveContext[]} */
  const kept = []
  const keep = { run(/** @type {import('..').DirectiveContext} */ ctx) { kept.push(ctx); return [] } }
  new Parser({ directives: { keep } }).parse('.. keep::\n')
  assert.throws(() => kept[0].parseInline('x'), /has returned/)
})

test('a directive may parse a document of its own', () => {
  const inner = {
    run() {
      const doc = rst.parse('*inner*\n', { directives: { box } })
      return doc.children ?? []
    },
  }
  const doc = new Parser({ directives: { inner, box } }).parse('.. box::\n\n   .. inner::\n')
  assert.equal(rst.findAll(doc, 'emphasis').length, 1)
})

test('roles', () => {
  /** @type {import('..').RoleFunction} */
  const kbd = (ctx) => {
    if (ctx.text === '?') throw new DirectiveError(`unknown key in ${ctx.rawsource}`)
    return [{ kind: 'literal', attributes: { classes: ['kbd'] }, children: [{ text: ctx.text }], span: ctx.span }]
  }
  const parser = new Parser({ roles: { kbd } })
  const [literal] = rst.findAll(parser.parse('Press :kbd:`Ctrl\\+C`.\n'), 'literal')
  assert.equal(rst.astext(literal), 'Ctrl+C')
  assert.deepEqual(literal.span, { start: 6, end: 20 })
  const doc = parser.parse('Press :kbd:`?`.\n')
  assert.equal(rst.astext(rst.findAll(doc, 'problematic')[0]), ':kbd:`?`')
  assert.equal(rst.astext(rst.findAll(doc, 'system_message')[0]), 'unknown key in :kbd:`?`')
})

test('file access', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lsdocs-rst-'))
  try {
    fs.writeFileSync(path.join(dir, 'part.txt'), 'Included *text*.\n')
    const text = '.. include:: part.txt\n'
    assert.ok(rst.pformat(rst.parse(text)).includes('directive disabled'))
    assert.equal(rst.astext(rst.parse(text, { root: dir })), 'Included text.')
    const files = (/** @type {string} */ p) => fs.readFileSync(path.join(dir, p))
    assert.equal(rst.astext(rst.parse(text, { files })), 'Included text.')
    const missing = rst.astext(rst.parse('.. include:: nope.txt\n', { files }))
    assert.ok(missing.includes("[Errno 2] No such file or directory: 'nope.txt'"), missing)
    assert.throws(
      () => rst.parse(text, { files: () => { throw new TypeError('bug') } }),
      TypeError,
    )
  } finally {
    fs.rmSync(dir, { recursive: true, force: true })
  }
})
