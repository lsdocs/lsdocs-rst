"""Parsing, the tree, settings and writers."""

import json

import pytest

import lsdocs_rst
from lsdocs_rst import Element, Text

DOC = "Title\n=====\n\nHello, *world*.\n"


def test_module_example() -> None:
    doc = lsdocs_rst.parse(DOC, transforms=True)
    assert doc.kind == "document"
    assert doc["title"] == "Title"
    [emphasis] = doc.findall("emphasis")
    assert (emphasis.astext(), emphasis.span) == ("world", (20, 27))
    assert doc.pformat().startswith('<document ids="title" names="title" title="Title">\n')


def test_tree_access() -> None:
    doc = lsdocs_rst.parse("A *b* and **c**.\n\n- x\n- y\n")
    paragraph, bullet_list = doc
    assert paragraph.tagname == "paragraph"
    assert [e.kind for e in doc.traverse()] == [
        "document", "paragraph", "emphasis", "strong",
        "bullet_list", "list_item", "paragraph", "list_item", "paragraph",
    ]
    assert paragraph[0] == Text("A ", (0, 2))
    assert bullet_list.get("bullet") == "-"
    assert len(bullet_list) == 2
    assert doc.astext() == "A b and c.xy"


def test_dicts_round_trip_through_json() -> None:
    doc = lsdocs_rst.parse(DOC, transforms=True)
    data = json.loads(json.dumps(doc.to_dict()))
    assert Element.from_dict(data) == doc
    assert data["children"][1] == {
        "kind": "paragraph",
        "children": [
            {"text": "Hello, ", "span": {"start": 13, "end": 20}},
            {
                "kind": "emphasis",
                "children": [{"text": "world", "span": {"start": 20, "end": 27}}],
                "span": {"start": 20, "end": 27},
            },
            {"text": ".", "span": {"start": 27, "end": 28}},
        ],
        "span": {"start": 13, "end": 28},
    }


def test_built_trees_print() -> None:
    tree = Element("document", children=[Element("paragraph", {"classes": ["x"]}, [Text("hi")])])
    assert tree.pformat() == '<document>\n    <paragraph classes="x">\n        hi\n'
    assert tree.to_xml(xml_declaration=False, doctype_declaration=False) == (
        '<!-- Generated by lsdocs-rst -->\n<document><paragraph classes="x">hi</paragraph></document>'
    )


def test_settings() -> None:
    doc = lsdocs_rst.parse("See PEP 8.\n", pep_references=True)
    [reference] = doc.findall("reference")
    assert reference["refuri"] == "https://peps.python.org/pep-0008"
    parser = lsdocs_rst.Parser(tab_width=4, toc_backlinks="top")
    assert parser.settings["tab_width"] == 4
    assert parser.settings["toc_backlinks"] == "top"
    assert lsdocs_rst.default_settings()["auto_id_prefix"] == "%"
    with pytest.raises(ValueError, match="tabwidth"):
        lsdocs_rst.parse("x\n", tabwidth=4)


def test_messages() -> None:
    doc, messages = lsdocs_rst.Parser(transforms=True).parse_with_messages("See missing_.\n")
    [problematic] = doc.findall("problematic")
    [message] = messages
    assert problematic["refid"] in message["ids"]
    assert message.astext() == 'Unknown target name: "missing".'


def test_make_id() -> None:
    assert lsdocs_rst.make_id("Hello, World!") == "hello-world"


def test_files_need_a_loader(tmp_path) -> None:
    (tmp_path / "part.txt").write_text("Included *text*.\n")
    text = ".. include:: part.txt\n"
    assert "directive disabled" in lsdocs_rst.parse(text).pformat()
    assert lsdocs_rst.parse(text, root=tmp_path).astext() == "Included text."
